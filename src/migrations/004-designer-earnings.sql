
BEGIN;

CREATE TABLE IF NOT EXISTS designer_earnings (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    pedido_id BIGINT NOT NULL
        REFERENCES pedidos(id) ON DELETE RESTRICT,

    designer_artwork_id INTEGER NOT NULL
        REFERENCES designer_artworks(id) ON DELETE RESTRICT,

    designer_id INTEGER NOT NULL
        REFERENCES designers(id) ON DELETE RESTRICT,

    valor_venda NUMERIC(10,2) NOT NULL
        CHECK (valor_venda >= 0),

    percentual_comissao NUMERIC(5,2) NOT NULL DEFAULT 40.00
        CHECK (
            percentual_comissao >= 0
            AND percentual_comissao <= 100
        ),

    valor_comissao NUMERIC(10,2) NOT NULL
        CHECK (valor_comissao >= 0),

    status VARCHAR(20) NOT NULL DEFAULT 'pendente'
        CHECK (
            status IN (
                'pendente',
                'enviado',
                'pago',
                'reprovado',
                'falha_envio'
            )
        ),

    criado_em TIMESTAMP WITHOUT TIME ZONE
        NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT designer_earnings_pedido_arte_unique
        UNIQUE (pedido_id, designer_artwork_id)
);

CREATE INDEX IF NOT EXISTS idx_designer_earnings_designer_status
    ON designer_earnings (designer_id, status);

CREATE INDEX IF NOT EXISTS idx_designer_earnings_pedido
    ON designer_earnings (pedido_id);

COMMIT;
